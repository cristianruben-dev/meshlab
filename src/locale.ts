export function diagnostic(language: Language, text: string, fileOperation = false): string {
  if (language === 'en') return text
  for (const [pattern, replacement] of diagnostics) {
    const match = pattern.exec(text)
    if (match) return replacement.replace(/\$(\d+)/g, (_, group: string) => match[Number(group)] ?? '')
  }
  return fileOperation ? 'No se pudo procesar el archivo. Comprueba que sea un circuito JSON válido.' : 'Revisa las conexiones y los valores del circuito.'
}
